"""Generate the router-side access installer from the app's own read requests.

The wrapper and the collector are built from the same command tables, so the
router always accepts exactly what this version of the app asks for and
nothing else. Run the installer once over a password SSH session.
"""
import re
from .collector import COMMANDS, PORT_COMMANDS, request_script
from .dhcp import DHCP_COMMANDS, dhcp_request_script
from .firewall import FIREWALL_COMMANDS, firewall_request_script

WRAPPER_PATH = '/etc/dropbear/cypress-forge-readonly.sh'
KEY_OPTIONS = ('command="%s",no-port-forwarding,no-agent-forwarding,'
               'no-X11-forwarding,no-pty' % WRAPPER_PATH)
PUBKEY_RE = re.compile(r'^(ssh-ed25519) ([A-Za-z0-9+/]+={0,2})(?: [ -~]{0,100})?$')

# (label, exact request string the collector sends, commands the wrapper runs)
REQUESTS = [
    ('base', request_script(False), COMMANDS),
    ('ports', request_script(True), PORT_COMMANDS),
    ('firewall', firewall_request_script(), FIREWALL_COMMANDS),
    ('dhcp', dhcp_request_script(), DHCP_COMMANDS),
]


def parse_public_key(text):
    """Return (type, base64 blob) of a single ed25519 public key line."""
    line = text.strip()
    match = PUBKEY_RE.match(line)
    if not match or '\n' in line:
        raise ValueError('Expected one ssh-ed25519 public key line')
    return match.group(1), match.group(2)


def wrapper_script():
    """Forced-command gate: compare the request exactly, then run fixed commands."""
    out = ['#!/bin/sh', '# Generated by Cypress Forge. Read-only collector gate.',
           'set -eu', 'PATH=/usr/sbin:/usr/bin:/sbin:/bin', 'export PATH']
    for label, request, _ in REQUESTS:
        tag = 'CF_REQ_' + label.upper()
        out += ['%s=$(cat <<\'%s\'' % (tag, tag), request, tag, ')']
    out.append('case "${SSH_ORIGINAL_COMMAND-}" in')
    for label, _, _ in REQUESTS:
        out.append('    "$CF_REQ_%s") KIND=%s ;;' % (label.upper(), label))
    out.append("    *) printf '%s\\n' 'Cypress Forge: command denied (read-only collector key).' >&2; exit 126 ;;")
    out.append('esac')
    out.append('case "$KIND" in')
    for label, _, commands in REQUESTS:
        out.append('    %s)' % label)
        for name, cmd in commands.items():
            out.append("        printf '\\n__CF_%s__\\n'" % name)
            out.append('        ' + cmd)
        out.append('        ;;')
    out.append('esac')
    return '\n'.join(out) + '\n'


def installer_script(public_key_text):
    key_type, blob = parse_public_key(public_key_text)
    key_prefix = '%s %s %s' % (KEY_OPTIONS, key_type, blob)
    key_line = key_prefix + ' Cypress Forge collector'
    wrapper = wrapper_script()
    assert 'CF_WRAPPER_END' not in wrapper
    return f'''#!/bin/sh
# Cypress Forge router access installer (generated). Contains a PUBLIC key only.
# Adds one restricted, read-only collector key and its command gate.
# Does not change firewall, network, passwords or the SSH service.
set -eu
PATH=/usr/sbin:/usr/bin:/sbin:/bin
export PATH
umask 077
R="${{CF_TEST_ROOT-}}"
if [ -z "$R" ]; then
    [ "$(id -u)" = 0 ] || {{ echo 'Run this as root on the router.' >&2; exit 1; }}
    command -v dropbear >/dev/null || {{ echo 'Dropbear SSH was not found. Nothing changed.' >&2; exit 1; }}
fi
DIR="$R/etc/dropbear"
KEYS="$DIR/authorized_keys"
GATE="$R{WRAPPER_PATH}"
[ -d "$DIR" ] && [ ! -L "$DIR" ] || {{ echo 'Unexpected /etc/dropbear. Nothing changed.' >&2; exit 1; }}
if [ -L "$KEYS" ] || {{ [ -e "$KEYS" ] && [ ! -f "$KEYS" ]; }}; then
    echo 'Unexpected authorized_keys file type. Nothing changed.' >&2; exit 1
fi
[ ! -L "$GATE" ] || {{ echo 'Collector gate is a symlink. Nothing changed.' >&2; exit 1; }}
BACKUP=$(mktemp -d "$DIR/cypress-forge-backup.XXXXXX")
[ -f "$KEYS" ] && cp -p "$KEYS" "$BACKUP/authorized_keys.before"
[ -f "$GATE" ] && cp -p "$GATE" "$BACKUP/gate.before"
cat > "$BACKUP/gate.new" <<'CF_WRAPPER_END'
{wrapper}CF_WRAPPER_END
/bin/sh -n "$BACKUP/gate.new"
chmod 700 "$BACKUP/gate.new"
if [ -f "$GATE" ] && cmp -s "$BACKUP/gate.new" "$GATE"; then
    echo 'Collector gate: already current.'
else
    cp -p "$BACKUP/gate.new" "$GATE.tmp" && mv "$GATE.tmp" "$GATE"
    echo 'Collector gate: installed.'
fi
KEY_LINE='{key_line}'
KEY_PREFIX='{key_prefix}'
if [ -f "$KEYS" ] && grep -Fq "$KEY_PREFIX" "$KEYS"; then
    echo 'Collector key: already installed.'
elif [ -f "$KEYS" ] && grep -Fq '{blob}' "$KEYS"; then
    echo 'This key already has a different access entry. Key not changed; review authorized_keys.' >&2
    exit 2
else
    {{ [ -f "$KEYS" ] && cat "$KEYS"; printf '%s\\n' "$KEY_LINE"; }} > "$BACKUP/authorized_keys.new"
    chmod 600 "$BACKUP/authorized_keys.new"
    mv "$BACKUP/authorized_keys.new" "$KEYS"
    echo 'Collector key: installed (read-only, no shell, no forwarding).'
fi
echo "Backup: $BACKUP"
echo 'Done. No firewall, network, password or service changes were made.'
'''


def removal_script(public_key_text):
    """Revoke the collector key; leaves every other access entry untouched."""
    _, blob = parse_public_key(public_key_text)
    return f'''#!/bin/sh
set -eu
umask 077
R="${{CF_TEST_ROOT-}}"
KEYS="$R/etc/dropbear/authorized_keys"
[ -f "$KEYS" ] || {{ echo 'No authorized_keys file. Nothing to remove.'; exit 0; }}
grep -Fv '{blob}' "$KEYS" > "$KEYS.cf-new" || true
chmod 600 "$KEYS.cf-new" && mv "$KEYS.cf-new" "$KEYS"
echo 'Cypress Forge collector key removed. Other access entries were not changed.'
'''
